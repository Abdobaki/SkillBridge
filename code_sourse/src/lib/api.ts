export async function signUpUser(email: string, password: string, name: string, role: string, profession: string = '', country: string = '') {
  const { data, error } = await supabase.auth.signUp({
    email,
    password,
    options: {
      data: { full_name: name, role: role, profession: profession, country: country }
    }
  });
  if (error) throw error;
  return data;
}

export async function signInUser(email: string, password: string) {
  const { data, error } = await supabase.auth.signInWithPassword({ email, password });
  if (error) throw error;
  return data;
}

export async function signInWithGoogle() {
  const isNative = Capacitor.isNativePlatform();
  const redirectTo = isNative ? 'com.skillbridge.app://login-callback' : window.location.origin;

  const { data, error } = await supabase.auth.signInWithOAuth({
    provider: 'google',
    options: {
      redirectTo: redirectTo,
      skipBrowserRedirect: isNative
    }
  });
  if (error) throw error;

  if (isNative && data?.url) {
    await Browser.open({ url: data.url });
  }
  return data;
}

