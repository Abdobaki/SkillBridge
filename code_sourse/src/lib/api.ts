export interface NotificationPrefs {
  newCourses: boolean;
  jobUpdates: boolean;
  enrollments: boolean;
  promotional: boolean;
}

/** Save notification preferences to the users table in Supabase */
export async function saveNotificationPrefs(prefs: NotificationPrefs) {
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return;

  // Best-effort — columns may not exist yet; errors are silently ignored
  await supabase
    .from('users')
    .update({
      notify_new_courses: prefs.newCourses,
      notify_job_updates: prefs.jobUpdates,
      notify_enrollments: prefs.enrollments,
      notify_promotional: prefs.promotional,
    })
    .eq('id', user.id)
    .then(({ error }) => {
      if (error) console.warn('Could not save notification prefs to DB:', error.message);
    });
}

/** Trigger a notification email for all opted-in users (called after admin approves course/job) */
export async function triggerNotification(
  type: 'new_course' | 'new_job',
  payload: Record<string, unknown>
) {
  await supabase.functions.invoke('send-notification', { body: { type, payload } });
}
