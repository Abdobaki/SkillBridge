export async function joinCourse(
  courseId: string,
  courseTitle: string,
  studentName: string,
  studentEmail: string
) {
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) throw new Error('Not authenticated');

  // Check not already enrolled
  const { data: existing } = await supabase
    .from('enrollments')
    .select('id')
    .eq('course_id', courseId)
    .eq('student_email', studentEmail)
    .maybeSingle();

  if (existing) throw new Error('Already enrolled in this course');

  const payload = {
    course_id: courseId,
    student_name: studentName,
    student_email: studentEmail,
    enrolled_date: new Date().toISOString(),
    status: 'enrolled',
    progress: 0,
  };

  const { data, error } = await supabase
    .from('enrollments')
    .insert(payload)
    .select()
    .single();
  if (error) throw error;

  // Increment enrolled count on the course (best-effort — ignore if RPC not set up)
  supabase.rpc('increment_course_enrollment', { course_id_param: courseId }).catch(() => {});

  // Send enrollment confirmation email (best-effort)
  supabase.functions.invoke('send-notification', {
    body: {
      type: 'enrollment_confirmation',
      payload: { userEmail: studentEmail, userName: studentName, courseTitle },
    },
  }).catch(() => {});

  return toCamelCase(data) as Enrollment;
}

export async function leaveCourse(enrollmentId: string, courseId: string) {
  const { data: enrollment, error: fetchError } = await supabase
    .from('enrollments')
    .select('enrolled_date')
    .eq('id', enrollmentId)
    .single();

  if (fetchError || !enrollment) throw new Error('Enrollment not found');

  const enrolledAt = new Date(enrollment.enrolled_date);
  const hoursSinceJoin = (Date.now() - enrolledAt.getTime()) / (1000 * 60 * 60);

  if (hoursSinceJoin > 24) {
    throw new Error('You can only leave within 24 hours of joining');
  }

  const { error } = await supabase
    .from('enrollments')
    .delete()
    .eq('id', enrollmentId);
  if (error) throw error;

  // Decrement enrolled count on the course (best-effort — ignore if RPC not set up)
  supabase.rpc('decrement_course_enrollment', { course_id_param: courseId }).catch(() => {});
}

