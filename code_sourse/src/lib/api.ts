export async function saveProposal(proposal: Partial<CourseProposal>) {
  const { id, ...withoutId } = proposal;
  // If id starts with 'prop' it's a frontend generated mock ID, we need to omitt it for Supabase to gen UUID
  const isExisting = id && !id.startsWith('prop');

  const payload = toSnakeCase(isExisting ? proposal : withoutId);

  const { data: { user } } = await supabase.auth.getUser();
  if (user && !isExisting) {
    payload.trainer_id = user.id;
  }

  if (isExisting) {
    const { data, error } = await supabase.from('course_proposals').update(payload).eq('id', id).select().single();
    if (error) throw error;
    return toCamelCase(data) as CourseProposal;
  } else {
    const { data, error } = await supabase.from('course_proposals').insert(payload).select().single();
    if (error) throw error;
    return toCamelCase(data) as CourseProposal;
  }
}

